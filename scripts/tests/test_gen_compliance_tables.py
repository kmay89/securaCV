#!/usr/bin/env python3
"""Tests for scripts/gen_compliance_tables.py — the tables are the maps, rendered.

The generator turns docs/compliance/maps/*.json into the human tables beside
them and into STATUS.md. These tests pin its byte layout on a fixture map,
the dagger-and-footnote rule for unverified clauses, the escaping, the links
(which must resolve the way scripts/lint_md_links.py resolves them), the
STATUS.md counts and crosswalk, the refusal to render a map the linter
rejects, and --check's two failure modes (stale, orphan). The last test
holds the committed tables to the committed maps. Each test except that one
runs in a temporary tree via --root; nothing touches the network.

Run:  python3 -m unittest discover -s scripts/tests -p 'test_gen_compliance_tables.py' -v
CI:   .github/workflows/lint.yml (unittest discover -s scripts/tests; and the
      generator's own --check step)
"""
from __future__ import annotations

import io
import json
import subprocess
import sys
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "scripts" / "gen_compliance_tables.py"
sys.path.insert(0, str(REPO / "scripts"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_compliance_tables as G  # noqa: E402
import lint_md_links  # noqa: E402
from test_lint_compliance_map import Tree  # noqa: E402

P = "gen_compliance_tables: "

EXPECTED_FIXTURE = """\
<!-- GENERATED by scripts/gen_compliance_tables.py from docs/compliance/maps/fixture.json — edit the map, then run the generator -->
# Fixture regime: clause → mechanism → status

This table maps clauses to SecuraCV mechanisms. It is not a determination: the fixture regulator decides whether a deployment's records and controls are acceptable. The receipt ledgers are the record; this table points at them. Status words: [STATUS.md](STATUS.md). The frame: [README.md](README.md).

Source: Fixture 1 — not fetched (blocked); requirement text is our paraphrase and every clause marked † is unverified: not fetched

A paragraph.

| Clause | Requirement (our paraphrase) | Mechanism | Status | Evidence | The operator must | Limits |
|---|---|---|---|---|---|---|
| 1.1†<br>row `s1` | r | m | **structural** | test `real_test` in [`src/lib.rs`](../../src/lib.rs)<br>[`src/lib.rs`](../../src/lib.rs) `pub fn append_thing(` | — | — |
| 1.2†<br>row `p1` | r | m | **procedural** | [`docs/runbook.md`](../runbook.md#step-one) | do it | — |
| 1.3†<br>row `d1` | r | m | **designed** (needs item3:F) | [`spec/design.md`](../../spec/design.md#layer-3) | — | — |
| 1.4†<br>row `n1` | r | m | **not-applicable** | — | — | This requirement addresses a kind of system this is not. |
| 1.5†<br>row `x1` | r | m | **not-pursued** | decision: [`spec/invariants.md`](../../spec/invariants.md#invariant-iii) | — | Deliberately not provided; the decision is recorded in the invariants. |
| 1.6†<br>row `k1` | r | m | **procedural** — software gap tracked | [`docs/runbook.md`](../runbook.md)<br>tracker: [`docs/security/ENTERPRISE_CUSTODY.md`](../security/ENTERPRISE_CUSTODY.md#6-regulated-market-assurance-tier) | stand in | — |

† Paraphrased; the clause text was not checked against its source in this review. Read the source before relying on the row.

Counts: 1 structural · 2 procedural · 1 designed · 1 not-applicable · 1 not-pursued.
"""

CROSSWALK_COMMENT = ("The closed status set. Crosswalk: CEREMONY_RUNBOOK CODE -> structural; PROC -> procedural; "
                     "GAP -> procedural with a tracker. CPS shipped -> structural; not provided -> the same three as GAP.")


def run(root: Path, *args: str) -> tuple[int, str, str]:
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        code = G.main(["--root", str(root), *args])
    return code, out.getvalue(), err.getvalue()


class Generator(unittest.TestCase):
    def tree(self) -> Tree:
        t = Tree(self)
        data = json.loads((t.root / "spec/witness_dictionary.json").read_text())
        data["compliance_map_status"]["$comment"] = CROSSWALK_COMMENT
        t.write("spec/witness_dictionary.json", json.dumps(data))
        t.write_map()
        return t

    def table(self, t: Tree, stem: str = "fixture") -> str:
        code, _out, err = run(t.root)
        self.assertEqual(code, 0, err)
        return (t.root / f"docs/compliance/{stem}.md").read_text(encoding="utf-8")

    def test_render_fixture_map_byte_exact(self):
        self.assertEqual(self.table(self.tree()), EXPECTED_FIXTURE)

    def test_dagger_and_footnote_only_when_unverified(self):
        t = self.tree()
        t.map["regime"]["source"]["access"] = "fetched"
        for r in t.map["rows"]:
            r["clause_verified"] = True
        t.write_map()
        text = self.table(t)
        self.assertNotIn("†", text)
        self.assertIn("\nSource: Fixture 1 — fetched\n", text)
        self.assertIn("| 1.1<br>row `s1` |", text)

    def test_pipe_escaped(self):
        t = self.tree()
        t.map["rows"][0]["mechanism"] = "a | b"
        t.write_map()
        self.assertIn("| a \\| b |", self.table(t))

    def test_evidence_links_relative_and_resolve(self):
        t = self.tree()
        self.table(t)
        saved = lint_md_links.ROOT
        try:
            lint_md_links.ROOT = t.root.resolve()
            problems = []
            for f in sorted((t.root / "docs/compliance").glob("*.md")):
                problems += lint_md_links.check_file(f.resolve(), {})
        finally:
            lint_md_links.ROOT = saved
        self.assertEqual(problems, [])

    def test_status_counts_and_crosswalk_table(self):
        t = self.tree()
        self.table(t)
        status = (t.root / "docs/compliance/STATUS.md").read_text(encoding="utf-8")
        for line in ("| CEREMONY_RUNBOOK | CODE | structural |",
                     "| CEREMONY_RUNBOOK | PROC | procedural |",
                     "| CEREMONY_RUNBOOK | GAP | procedural with a tracker |",
                     "| CPS | shipped | structural |",
                     "| CPS | not provided | the same three as GAP |",
                     "| [fixture](fixture.md) | 1 | 2 | 1 | 1 | 1 | 6 |",
                     "| **total** | 1 | 2 | 1 | 1 | 1 | 6 |",
                     "| **structural** | d | — |"):
            with self.subTest(line=line):
                self.assertIn(line, status)

    def test_refuses_map_with_lint_findings(self):
        t = self.tree()
        t.row("s1")["evidence"][0]["test"] = "invented_test"
        t.write_map()
        code, out, err = run(t.root)
        self.assertEqual((code, out), (1, ""))
        self.assertEqual(err, P + "maps/fixture.json has lint findings — run python3 scripts/lint_compliance_map.py\n")
        self.assertFalse((t.root / "docs/compliance/fixture.md").exists())

    def test_check_detects_stale(self):
        t = self.tree()
        self.table(t)
        t.map["rows"][0]["mechanism"] = "changed"
        t.write_map()
        code, out, err = run(t.root, "--check")
        self.assertEqual((code, out), (1, ""))
        self.assertIn(P + "docs/compliance/fixture.md is stale — run python3 scripts/gen_compliance_tables.py\n", err)
        # STATUS.md carries no mechanism text, so it is still current.
        self.assertNotIn("STATUS.md", err)

    def test_check_detects_orphan(self):
        t = self.tree()
        self.table(t)
        (t.root / "docs/compliance/maps/fixture.json").unlink()
        code, out, err = run(t.root, "--check")
        self.assertEqual(code, 1)
        self.assertIn(P + "docs/compliance/fixture.md is generated but maps/fixture.json is gone — delete it or "
                          "restore the map\n", err)
        code, out, _err = run(t.root)
        self.assertEqual(code, 0)
        self.assertFalse((t.root / "docs/compliance/fixture.md").exists())

    def test_output_byte_stable_across_runs(self):
        t = self.tree()
        self.table(t)
        first = {p.name: p.read_bytes() for p in (t.root / "docs/compliance").glob("*.md")}
        self.table(t)
        second = {p.name: p.read_bytes() for p in (t.root / "docs/compliance").glob("*.md")}
        self.assertEqual(first, second)
        for name, data in second.items():
            with self.subTest(name=name):
                self.assertNotIn(b"\r", data)
                self.assertTrue(data.endswith(b"\n") and not data.endswith(b"\n\n"))
        code, out, err = run(t.root, "--check")
        self.assertEqual((code, err), (0, ""))
        self.assertEqual(out, P + "2 file(s) current\n")

    def test_repo_tables_current(self):
        proc = subprocess.run([sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertRegex(proc.stdout, r"^gen_compliance_tables: \d+ file\(s\) current\n$")


if __name__ == "__main__":
    unittest.main()
