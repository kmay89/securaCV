#!/usr/bin/env python3
"""Generate the compliance tables from the compliance maps — never the other way round.

    python3 scripts/gen_compliance_tables.py            # write the tables
    python3 scripts/gen_compliance_tables.py --check    # CI: fail if any is stale
    python3 scripts/gen_compliance_tables.py --root DIR # a test tree

Inputs: docs/compliance/maps/*.json and the `compliance_map_status` block of
spec/witness_dictionary.json. Outputs: docs/compliance/<stem>.md, one per
map, and docs/compliance/STATUS.md (the five statuses, the crosswalk from the
runbook's and the CPS's status words, and the counts per map). From item 7's
CP3 it also renders spec/rulesets/<slug>.md.

A table is a reader's view of a map; the map is what the linter holds to the
disk. So this generator imports the linter's loader and refuses to render a
map with any schema, status, evidence, depends_on or clause finding (rules
S/V/E/D/C of scripts/lint_compliance_map.py): a table never shows a row the
gate would reject. Output is deterministic — rows in map order, LF endings,
one trailing newline, no timestamps — so --check is a byte comparison.

Stdlib only. The tests: scripts/tests/test_gen_compliance_tables.py.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lint_compliance_map as lint  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
PREFIX = "gen_compliance_tables: "
OUT_DIR = "docs/compliance"
STATUS_FILE = "STATUS.md"
REFUSING_RULES = ("S", "V", "E", "D", "C")
GENERATED_TAG = "<!-- GENERATED by scripts/gen_compliance_tables.py from docs/compliance/maps/"
FOOTNOTE = ("† Paraphrased; the clause text was not checked against its source in this review. "
            "Read the source before relying on the row.")
STATUS_HEADER = ("<!-- GENERATED by scripts/gen_compliance_tables.py from spec/witness_dictionary.json "
                 "(compliance_map_status) and docs/compliance/maps/*.json — edit those, then run the generator -->")


class Refusal(Exception):
    pass


def cell(text: str) -> str:
    text = text.strip().replace("|", "\\|")
    return text if text else "—"


def rel_link(path: str) -> str:
    return os.path.relpath(path, OUT_DIR).replace(os.sep, "/")


def evidence_cell(ev: dict) -> str:
    kind, p = ev["kind"], ev["path"]
    target = rel_link(p) + (f"#{ev['anchor']}" if ev.get("anchor") else "")
    link = f"[`{p}`]({target})"
    if kind == "test":
        text = f"test `{ev['test']}` in {link}"
    elif ev.get("symbol"):
        text = f"{link} `{ev['symbol']}`"
    else:
        text = link
    if kind in ("decision", "tracker"):
        text = f"{kind}: {text}"
    return text


def status_cell(row: dict) -> str:
    out = f"**{row['status']}**"
    if row["status"] == "designed" and row.get("depends_on"):
        out += f" (needs {', '.join(row['depends_on'])})"
    if any(e["kind"] == "tracker" for e in row["evidence"]):
        out += " — software gap tracked"
    return out


def counts_of(rows: list[dict]) -> dict[str, int]:
    counts = {s: 0 for s in lint.STATUSES}
    for r in rows:
        counts[r["status"]] += 1
    return counts


def render_map(stem: str, data: dict) -> str:
    regime, source = data["regime"], data["regime"]["source"]
    rows = data["rows"]
    out = [
        f"<!-- GENERATED by scripts/gen_compliance_tables.py from docs/compliance/maps/{stem}.json — "
        "edit the map, then run the generator -->",
        f"# {regime['title']}: clause → mechanism → status",
        "",
        "This table maps clauses to SecuraCV mechanisms. It is not a determination: "
        f"{regime['determination_by']} decides whether a deployment's records and controls are acceptable. "
        "The receipt ledgers are the record; this table points at them. Status words: [STATUS.md](STATUS.md). "
        "The frame: [README.md](README.md).",
        "",
    ]
    if source["access"] == "fetched":
        out.append(f"Source: {source['citation']} — fetched")
    else:
        out.append(f"Source: {source['citation']} — not fetched ({source['access']}); requirement text is our "
                   f"paraphrase and every clause marked † is unverified: {source['note']}")
    out.append("")
    for para in data.get("preamble", []):
        out += [para, ""]
    out += ["| Clause | Requirement (our paraphrase) | Mechanism | Status | Evidence | The operator must | Limits |",
            "|---|---|---|---|---|---|---|"]
    dagger = False
    for r in rows:
        clause = r["clause"] + ("" if r["clause_verified"] else "†")
        dagger = dagger or not r["clause_verified"]
        if r["id"] != r["clause"]:
            clause += f"<br>row `{r['id']}`"
        limits = " — ".join(x for x in (r.get("reason", ""), r.get("limits", "")) if x.strip())
        evidence = "<br>".join(evidence_cell(e) for e in r["evidence"])
        out.append("| " + " | ".join([
            cell(clause), cell(r["requirement"]), cell(r["mechanism"]), cell(status_cell(r)),
            cell(evidence), cell(r.get("operator_action", "")), cell(limits)]) + " |")
    out.append("")
    if dagger:
        out += [FOOTNOTE, ""]
    c = counts_of(rows)
    out.append("Counts: " + " · ".join(f"{c[s]} {s}" for s in lint.STATUSES) + ".")
    return "\n".join(out) + "\n"


def parse_crosswalk(comment: str) -> list[tuple[str, str, str]]:
    """[(source document, its word, the map status)] from the block's $comment."""
    if "Crosswalk: " not in comment:
        raise Refusal("spec/witness_dictionary.json compliance_map_status has no crosswalk in its $comment")
    text = comment.split("Crosswalk: ", 1)[1].strip()
    out = []
    for part in re.split(r"(?<=\.) (?=[A-Z_]+ )", text):
        part = part.strip().rstrip(".")
        doc, rest = part.split(" ", 1)
        for item in rest.split("; "):
            if " -> " not in item:
                raise Refusal(f"spec/witness_dictionary.json compliance_map_status crosswalk item {item!r} "
                              "has no ' -> '")
            word, status = item.split(" -> ", 1)
            out.append((doc, word.strip(), status.strip()))
    return out


def render_status(block: dict, maps: list[tuple[str, dict]]) -> str:
    out = [STATUS_HEADER, "# Compliance map statuses", "",
           "Every row of every map carries exactly one of these statuses. They are defined once, in "
           "`spec/witness_dictionary.json` (`compliance_map_status`), and describe a SecuraCV mechanism, never a "
           "deployment's standing under a regime. The frame: [README.md](README.md).", "",
           "| Status | Meaning | What a row must carry |", "|---|---|---|"]
    for item in block["items"]:
        carry = ", ".join(f"`{x}`" for x in item["requires"])
        out.append(f"| **{item['id']}** | {cell(item['definition'])} | {cell(carry)} |")
    out += ["", "## Crosswalk", "",
            "How the status words of the ceremony runbook and the Custody Practice Statement template map onto "
            "these.", "", "| Document | Its word | Map status |", "|---|---|---|"]
    for doc, word, status in parse_crosswalk(block["$comment"]):
        out.append(f"| {cell(doc)} | {cell(word)} | {cell(status)} |")
    out += ["", "## Counts per map", "",
            "| Map | " + " | ".join(lint.STATUSES) + " | rows |",
            "|---|" + "---|" * (len(lint.STATUSES) + 1)]
    totals = {s: 0 for s in lint.STATUSES}
    for stem, data in maps:
        c = counts_of(data["rows"])
        for s in lint.STATUSES:
            totals[s] += c[s]
        out.append(f"| [{stem}]({stem}.md) | " + " | ".join(str(c[s]) for s in lint.STATUSES)
                   + f" | {len(data['rows'])} |")
    out.append("| **total** | " + " | ".join(str(totals[s]) for s in lint.STATUSES)
               + f" | {sum(totals.values())} |")
    return "\n".join(out) + "\n"


def build(root: Path) -> dict[str, str]:
    """{repo-relative output path: content}. Raises Refusal."""
    statuses, s0 = lint.read_statuses(root)
    if s0:
        raise Refusal("spec/witness_dictionary.json compliance_map_status has lint findings — run "
                      "python3 scripts/lint_compliance_map.py")
    block = json.loads((root / lint.DICTIONARY).read_text(encoding="utf-8"))["compliance_map_status"]
    maps = []
    maps_dir = root / lint.MAPS_DIR
    for path in sorted(maps_dir.glob("*.json")) if maps_dir.is_dir() else []:
        refusal = (f"maps/{path.name} has lint findings — run python3 scripts/lint_compliance_map.py")
        try:
            data, findings = lint.lint_map(path, root, statuses)
        except lint.ParseError:
            raise Refusal(refusal) from None
        if data is None or any(f.rule.startswith(REFUSING_RULES) for f in findings):
            raise Refusal(refusal)
        maps.append((path.stem, data))
    outputs = {f"{OUT_DIR}/{stem}.md": render_map(stem, data) for stem, data in maps}
    outputs[f"{OUT_DIR}/{STATUS_FILE}"] = render_status(block, maps)
    return outputs


def orphans(root: Path, outputs: dict[str, str]) -> list[str]:
    found = []
    out_dir = root / OUT_DIR
    for f in sorted(out_dir.glob("*.md")) if out_dir.is_dir() else []:
        rel = f.relative_to(root).as_posix()
        if rel in outputs:
            continue
        try:
            first = f.read_text(encoding="utf-8").split("\n", 1)[0]
        except OSError:
            continue
        if first.startswith(GENERATED_TAG):
            found.append(rel)
    return found


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if a committed table differs from the maps")
    ap.add_argument("--root", type=Path, default=REPO, help="the repository root (tests use a temp tree)")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    try:
        outputs = build(root)
    except Refusal as e:
        print(PREFIX + str(e), file=sys.stderr)
        return 1
    stale = orphans(root, outputs)
    if args.check:
        problems = []
        for rel, text in outputs.items():
            p = root / rel
            if not p.is_file() or p.read_bytes() != text.encode("utf-8"):
                problems.append(f"{rel} is stale — run python3 scripts/gen_compliance_tables.py")
        for rel in stale:
            stem = Path(rel).stem
            problems.append(f"{rel} is generated but maps/{stem}.json is gone — delete it or restore the map")
        for msg in problems:
            print(PREFIX + msg, file=sys.stderr)
        if problems:
            return 1
        print(PREFIX + f"{len(outputs)} file(s) current")
        return 0
    for rel, text in outputs.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    for rel in stale:
        (root / rel).unlink()
        print(PREFIX + f"removed {rel} (its map is gone)")
    print(PREFIX + f"wrote {len(outputs)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
