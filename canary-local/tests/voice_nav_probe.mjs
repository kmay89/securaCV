// canary-local/tests/voice_nav_probe.mjs — rot guard for the Canary Voice
// sound board's place in the site.
//
// The board (canary-local/voice/index.html) is a hand-written page whose sound
// data, voice/voice-data.js, is generated from the firmware and content-gated by
// gen_voice_preview.mjs --check. THIS probe guards the other way it could rot:
// silently losing its spot in the navigation, or the page losing its data. It
// asserts the page exists and loads the generated (not a hand-edited) data file
// before its UI, and that it is registered in the ONE manifest every nav
// surface reads (build-line.json → htmlDocumentation), so the
// sitemap/room/app never miss it. Dependency-free (node stdlib) — no browser
// needed; tests/csp_probe.mjs is the one that plays it in Chromium.
//
//   node canary-local/tests/voice_nav_probe.mjs

import { readFileSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const LOCAL = join(ROOT, "canary-local");
const HREF = "voice/index.html";

let fail = 0;
const check = (cond, msg) => { if (!cond) { console.error(`  FAIL: ${msg}`); fail++; } };

// 1) The page exists and plays the GENERATED data (so nav points at the
//    rot-proof board, not a stale hand-copy of the sounds).
let page = "", data = "";
try { page = readFileSync(join(LOCAL, "voice", "index.html"), "utf8"); }
catch { console.error("  FAIL: canary-local/voice/index.html is missing"); fail++; }
try { data = readFileSync(join(LOCAL, "voice", "voice-data.js"), "utf8"); }
catch { console.error("  FAIL: canary-local/voice/voice-data.js is missing"); fail++; }
check(data.startsWith("// GENERATED by canary-local/tools/gen_voice_preview.mjs"),
      "voice/voice-data.js is the generated artifact (opens with the generator banner)");
check(data.includes("window.VOICE_DATA = "),
      "voice/voice-data.js carries the firmware-rendered VOICE_DATA");
check(!page.includes("window.VOICE_DATA"),
      "voice/index.html carries no copy of VOICE_DATA (the data lives in voice-data.js only)");
const scripts = [...page.matchAll(/<script\b[^>]*\ssrc="([^"]+)"/g)].map((m) => m[1]);
check(scripts.indexOf("voice-data.js") >= 0 && scripts.indexOf("voice-data.js") < scripts.indexOf("voice.js"),
      `voice/index.html loads voice-data.js before voice.js (found ${JSON.stringify(scripts)})`);

// 2) It is registered in the nav manifest that feeds every surface.
const manifest = JSON.parse(readFileSync(join(LOCAL, "build-line.json"), "utf8"));
const listed = (manifest.htmlDocumentation?.groups || [])
  .flatMap((g) => g.items || [])
  .some((i) => i.href === HREF);
check(listed,
      `build-line.json htmlDocumentation must list "${HREF}" — add it back so the ` +
      `sitemap and every nav surface keep the sound board reachable`);

if (fail) {
  console.error(`voice_nav_probe: ${fail} problem(s).`);
  process.exit(1);
}
console.log("voice_nav_probe: OK — sound board present, its data generated, and navigable.");
