// canary-local/assets/enclosure-lab.js — the parametric catalog, browsable.
//
// Every Canary enclosure is an OpenSCAD configurator; this lab is its
// showroom AND its print bench. Pick a variant, spin the actual printed
// parts (real STLs), dress them in your filament color, then flip to the
// print guide: the parts sit on a build plate exactly as modeled — the
// .scad sources put z=0 on the plate in the documented orientation — a
// layer slider scrubs a true cross-section of the mesh, overhang tint
// shows what would need support (these parts are designed not to), and
// the settings card quotes the repo's own guidance. A guide, not a
// slicer: nothing here is an invented toolpath.
//
// Data: devices/enclosures.json (generated by tools/gen_enclosures.py
// from docs/hardware/enclosure — README tables + .scad annotations).

